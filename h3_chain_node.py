"""MiniMax H3 clip chaining node for Apple Silicon, generated with h3.c.

[start image ->] clip 1 -> last frame -> clip 2 -> ... -> clip N -> merged video, inside one node.

Each clip is generated by a persistent h3.c worker (h3_backend) and cached in output/h3_cache/ under the
hash of everything that determines it, so a re-run, from any workflow, only regenerates the clips whose
inputs changed, and an interrupted run resumes. Save the merged video with Save Video.
"""

