from .h3_backend import H3Cancelled, get_worker, shutdown_worker

FPS = 24  # MiniMax H3 output frame rate
BACKEND = "h3.c"  # part of every clip cache key
VOICE_SECONDS = 15  # h3.c's limit for reference audio


def tensor_hash(image):
    return hashlib.sha256(image.cpu().numpy().tobytes()).hexdigest()


def save_png(image, path):
    Image.fromarray(np.clip(255.0 * image[0].cpu().numpy(), 0, 255).astype(np.uint8)).save(path)


def load_png(path):
    # Same conversion as LoadImage. Chaining always goes through the saved PNG so the next
    # clip sees identical input whether the previous clip was just generated or cached.
    return torch.from_numpy(np.array(Image.open(path).convert("RGB")).astype(np.float32) / 255.0)[None]


def save_voice(audio, cache_dir):
    """Write the first waveform of an AUDIO input as 16-bit WAV under its hash; h3.c decodes it with FFmpeg.
    h3.c rejects reference audio longer than 15 s, so longer samples keep only their first 15 s."""
    sample_rate = audio["sample_rate"]
    waveform = audio["waveform"][0]
    if waveform.shape[-1] > VOICE_SECONDS * sample_rate:
        logging.warning(f"MiniMax chain: voice is {waveform.shape[-1] / sample_rate:.1f} s, using its first {VOICE_SECONDS} s (h3.c limit).")
        waveform = waveform[..., :VOICE_SECONDS * sample_rate]
    pcm = (waveform.clamp(-1, 1) * 32767).round().to(torch.int16).movedim(0, -1).contiguous().cpu().numpy()
    path = os.path.join(cache_dir, hashlib.sha256(pcm.tobytes() + str(sample_rate).encode()).hexdigest() + ".wav")
    with wave.open(path, "wb") as f:
        f.setnchannels(pcm.shape[1])
        f.setsampwidth(2)
        f.setframerate(sample_rate)
        f.writeframes(pcm.tobytes())
    return path


def match_chroma(image, reference, strength):
    """Match the Lab a/b (color) statistics of `image` to `reference`. Luminance is left untouched,
    so contrast and black point (freckles, shadows) keep the generated frame's values."""
    lab = kornia.color.rgb_to_lab(image.movedim(-1, 1).float())
    ref = kornia.color.rgb_to_lab(reference.movedim(-1, 1).float())[:, 1:]
    ab = lab[:, 1:]
    mean, std = ab.mean((2, 3), keepdim=True), ab.std((2, 3), keepdim=True).clamp_min(1e-6)
    matched = (ab - mean) * (ref.std((2, 3), keepdim=True) / std) + ref.mean((2, 3), keepdim=True)
    lab[:, 1:] = torch.lerp(ab, matched, strength)
    return kornia.color.lab_to_rgb(lab).clamp(0, 1).movedim(1, -1)


def model_path(value):
    """Absolute path, or a path relative to ComfyUI's models folder."""
    path = Path(os.path.expanduser(value.strip()))
    return path if path.is_absolute() else Path(folder_paths.models_dir) / path


def format_seconds(seconds):
    minutes, seconds = divmod(seconds, 60)
    return f"{int(minutes)}:{seconds:04.1f}" if minutes else f"{seconds:.1f}s"


class ChainProgress:
    """Server: a console bar for the running h3.c phase, refreshed every second, and one log line per finished phase.
    UI: ComfyUI's progress bar counts denoising steps over the whole chain (clips x steps)."""

    def __init__(self, n, steps):
        self.n, self.steps = n, steps
        self.pbar = comfy.utils.ProgressBar(n * steps)
        self.lock = threading.Lock()
        self.generated, self.generated_seconds, self.cached = 0, 0.0, 0
        self.clip, self.phases, self.phase, self.bar, self.stop = None, {}, None, None, None

    def start_clip(self, i, seed):
        self.clip = i
        self.phases = {}  # phase -> [completed, total, seconds]
        self.start = self.last = time.perf_counter()
        logging.info(f"MiniMax chain: generating clip {i}/{self.n} (seed {seed})")
        self.stop = threading.Event()
        threading.Thread(target=self.tick, args=(self.stop,), name="minimax-chain-progress", daemon=True).start()

    def tick(self, stop):
        while not stop.wait(1.0):
            with self.lock:
                if not stop.is_set() and self.bar is not None:
                    self.bar.refresh()

    def update(self, phase, completed, total):
        with self.lock:
            now = time.perf_counter()
            state = self.phases.get(phase)
            repeated = phase != self.phase and state is not None and state[0] == completed == total
            if phase != self.phase and not repeated:
                self.end_phase()
                self.phase = phase
                self.bar = tqdm(total=total or None, desc=f"clip {self.clip}/{self.n} {phase}", leave=False)
            state = self.phases.setdefault(phase, [0, total, 0.0])
            # h3.c reports progress after the work it counts: the time since the previous event belongs to this phase.
            state[0], state[1], state[2] = completed, total, state[2] + now - self.last
            self.last = now
            if repeated:  # h3.c repeats some final events: count the time without reopening the phase
                return
            self.bar.update(completed - self.bar.n)
            # h3.c's GPU path reports each step on "denoise enqueue" and all of them at once on "denoise".
            if phase in ("denoise enqueue", "denoise") and total:
                self.pbar.update_absolute((self.clip - 1) * self.steps + completed * self.steps // total)
            if completed >= total:
                self.end_phase()

    def end_phase(self):
        if self.phase is None:
            return
        self.bar.close()
        completed, total, seconds = self.phases[self.phase]
        steps = f" {completed}/{total}" if total > 1 else ""
        logging.info(f"MiniMax chain: clip {self.clip}/{self.n} {self.phase}{steps} in {format_seconds(seconds)}")
        self.phase = self.bar = None

    def end_clip(self):
        with self.lock:
            self.stop.set()
            self.end_phase()
            seconds = time.perf_counter() - self.start
            self.generated += 1
            self.generated_seconds += seconds
            logging.info(f"MiniMax chain: clip {self.clip}/{self.n} done in {format_seconds(seconds)}")
            self.pbar.update_absolute(self.clip * self.steps)

    def abort(self):
        with self.lock:
            self.stop.set()
            if self.bar is not None:
                self.bar.close()
            self.phase = self.bar = None

    def skip_clip(self, i):
        self.cached += 1
        logging.info(f"MiniMax chain: clip {i}/{self.n} cached")
        self.pbar.update_absolute(i * self.steps)

    def finish(self):
        parts = [f"{self.generated} generated in {format_seconds(self.generated_seconds)}"] if self.generated else []
        if self.cached:
            parts.append(f"{self.cached} cached")
        logging.info(f"MiniMax chain: {self.n} clips: " + ", ".join(parts))


class MiniMaxH3ChainVideo(io.ComfyNode):
    @classmethod
    def define_schema(cls):
        return io.Schema(
            node_id="MiniMaxH3ChainVideoNative",
            display_name="MiniMax H3 Chain Video (h3.c)",
            category="video/minimax",
            description="Generates N consecutive MiniMax H3 clips with the native h3.c Metal engine, each starting from the last "
                        "frame of the previous one, and returns the merged video. Without a start image the first clip is text-to-video. "
                        "Finished clips are cached in output/h3_cache/: re-running only regenerates clips whose inputs changed.",
            inputs=[
                io.String.Input("model_dir", default="MiniMax-H3",
                                tooltip="MiniMax-H3 snapshot folder containing FL2VA/ (absolute, or relative to ComfyUI's models folder)."),
                io.Autogrow.Input("prompts", template=io.Autogrow.TemplateNames(
                    io.String.Input("prompt", tooltip="Prompt of this clip. Connect a Text (Multiline) node."),
                    names=[f"prompt_{i}" for i in range(1, 101)], min=1),
                    tooltip="One prompt per clip, in order: a new slot appears as you connect one."),
                io.String.Input("style", optional=True, force_input=True,
                                tooltip="Appended to every prompt. Connect a Text (Multiline) node."),
                io.Int.Input("num_clips", default=0, min=0, max=10000,
                             tooltip="0 = one clip per prompt. Fewer prompts than clips repeats the last prompt; extra prompts are ignored."),
                io.Float.Input("duration", default=5.0, min=0.9, max=150.0, step=0.1,
                               tooltip="Seconds per clip, snapped up to the model's 17k+5 frame grid (5 s = 124 frames)."),
                io.Int.Input("width", default=640, min=32, max=nodes.MAX_RESOLUTION, step=32),
                io.Int.Input("height", default=640, min=32, max=nodes.MAX_RESOLUTION, step=32),
                io.Int.Input("seed", default=0, min=0, max=0xffffffffffffffff, control_after_generate=True),
                io.Boolean.Input("vary_seed", default=True, tooltip="Use seed + clip index for each clip."),
                io.Image.Input("start_image", optional=True, tooltip="First frame of clip 1. Leave empty to generate clip 1 from text only."),
                io.Audio.Input("voice", optional=True,
                               tooltip="Voice sample (at least 2 s, longer ones are cut to 15 s) for the speech of every clip. Uses the Ref2VA checkpoint: each clip gets its start "
                                       "frame as <Picture 1> and this sample as <Audio 1> instead of a first-frame anchor, so seams are soft cuts. "
                                       "Needs start_image or reference_image."),
                io.Image.Input("reference_image", optional=True,
                               tooltip="Anti-drift reference (default: start_image, or clip 1's last frame without a start image)."),
                io.Int.Input("reanchor_every", default=0, min=0, max=10000,
                             tooltip="Anti-drift: re-inject the reference image every K clips (0 = off)."),
                io.Combo.Input("reanchor_mode", options=["target", "replace"], default="target",
                               tooltip="target: clips K, 2K... end on the reference (smooth). replace: clips K+1, 2K+1... start from it (hard cut)."),
                io.Float.Input("color_match", default=0.0, min=0.0, max=1.0, step=0.05,
                               tooltip="Match the colors (hue and saturation, not brightness or contrast) of each chained start frame "
                                       "to the reference image before generating the next clip. Counters skin-tone and color drift across clips. 0 = off."),
                io.Int.Input("denoise_steps", default=8, min=2, max=100,
                             tooltip="Actual h3.c denoising passes per clip (h3 --steps)."),
                io.Int.Input("reuse", default=1, min=1, max=3, advanced=True,
                             tooltip="Evaluate the denoiser on one of every N steps (h3 --reuse). 1 = exact, 2 fast, 3 aggressive. "
                                     "Cannot be combined with core_reuse > 1."),
                io.Int.Input("layers", default=50, min=35, max=50, advanced=True,
                             tooltip="DiT blocks kept (h3 --layers). 50 = exact, 45 fast, 40 aggressive."),
                io.Int.Input("core_reuse", default=1, min=1, max=8, advanced=True,
                             tooltip="Recompute the transformer core every N steps (h3 core reuse). 1 = exact, 4 fast, 6 aggressive."),
                io.Boolean.Input("token_reduction", default=False, advanced=True,
                                 tooltip="Pair adjacent video tokens through middle DiT blocks (aggressive speed mode)."),
                io.Int.Input("render_width", default=0, min=0, max=nodes.MAX_RESOLUTION, step=32, advanced=True,
                             tooltip="Lower internal canvas, upscaled to width x height. 0 = native. Set together with render_height, same aspect."),
                io.Int.Input("render_height", default=0, min=0, max=nodes.MAX_RESOLUTION, step=32, advanced=True),
                io.Boolean.Input("ssd_streaming", default=False, advanced=True,
                                 tooltip="Stream BF16 DiT blocks from disk: much less memory, slower."),
                io.Int.Input("redo_from", default=0, min=0, max=10000,
                             tooltip="Regenerate this clip and all following ones even if cached (0 = off). "
                                     "Needed after replacing the model files, which the disk cache does not track."),
                io.Boolean.Input("unload_after", default=False, advanced=True,
                                 tooltip="Stop the h3 worker after this run to free its memory. Off keeps the model warm for the next run."),
            ],
            outputs=[io.Video.Output(tooltip="All clips merged, without the duplicated frame at each seam. Connect Save Video to preview and save it.")],
        )

    @classmethod
    def execute(cls, model_dir, prompts: io.Autogrow.Type, num_clips, duration, width, height, seed, vary_seed, reanchor_every, reanchor_mode,
                color_match, denoise_steps, reuse, layers, core_reuse, token_reduction, render_width, render_height, ssd_streaming,
                redo_from, unload_after, style="", start_image=None, reference_image=None, voice=None) -> io.NodeOutput:
        try:
            return cls.run_chain(model_dir, prompts, style, num_clips, duration, width, height, seed, vary_seed, reanchor_every,
                                 reanchor_mode, color_match, denoise_steps, reuse, layers, core_reuse, token_reduction, render_width,
                                 render_height, ssd_streaming, redo_from, start_image, reference_image, voice)
        finally:
            if unload_after:
                shutdown_worker()

    @classmethod
    def run_chain(cls, model_dir, prompts, style, num_clips, duration, width, height, seed, vary_seed, reanchor_every, reanchor_mode,
                  color_match, steps, reuse, layers, core_reuse, token_reduction, render_width, render_height, ssd_streaming,
                  redo_from, start_image, reference_image, voice):
        prompt_list = [prompts[name].strip() for name in sorted(prompts, key=lambda name: int(name.removeprefix("prompt_")))
                       if prompts[name] and prompts[name].strip()]
        if not prompt_list:
            raise ValueError("No prompts: connect one text node per clip to the prompt inputs")
        n = num_clips or len(prompt_list)
        if len(prompt_list) < n:
            logging.warning(f"MiniMax chain: {len(prompt_list)} prompts for {n} clips, clips {len(prompt_list) + 1}-{n} reuse the last prompt.")
            prompt_list += [prompt_list[-1]] * (n - len(prompt_list))
        elif len(prompt_list) > n:
            logging.warning(f"MiniMax chain: {len(prompt_list)} prompts for {n} clips, ignoring the last {len(prompt_list) - n}.")
        suffix = f"\n\n{style.strip()}" if style.strip() else ""

        cache_dir = os.path.join(folder_paths.get_output_directory(), "h3_cache")
        os.makedirs(cache_dir, exist_ok=True)

        length = max(5, round(duration * FPS))  # h3.c snaps this up to 17k+5
        generation = {"steps": steps, "reuse": reuse, "layers": layers, "core_reuse": core_reuse, "token_reduction": token_reduction,
                      "render_width": render_width, "render_height": render_height}
        progress = ChainProgress(n, steps)
        worker = None

        # h3.c reads anchors from files: the start and reference images are written under their hash,
        # chained frames are the PNGs the worker wrote for the previous clip.
        prev_last, prev_last_file = None, None
        if start_image is not None:
            prev_last = start_image[:1]
            prev_last_file = os.path.join(cache_dir, f"{tensor_hash(prev_last)}.png")
            save_png(prev_last, prev_last_file)
        if reference_image is not None:
            reference = reference_image[:1]
            reference_file = os.path.join(cache_dir, f"{tensor_hash(reference)}.png")
            save_png(reference, reference_file)
        else:
            reference, reference_file = prev_last, prev_last_file
        voice_file = None
        if voice is not None:
            if reference is None:
                raise ValueError("voice needs start_image or reference_image: h3.c Ref2VA audio references must come with an image")
            voice_file = save_voice(voice, cache_dir)
            if prev_last is None:
                prev_last, prev_last_file = reference, reference_file
            if reanchor_every and reanchor_mode == "target":
                logging.warning("MiniMax chain: with a voice there are no last-frame anchors, reanchor_mode target behaves like replace.")
                reanchor_mode = "replace"

        videos = []
        for i in range(1, n + 1):
            reanchor = reanchor_every and i > 1 and (i - 1) % reanchor_every == 0 and reanchor_mode == "replace"
            first, first_file = (reference, reference_file) if reanchor else (prev_last, prev_last_file)
            target = reference is not None and reanchor_every and reanchor_mode == "target" and i % reanchor_every == 0
            prompt = prompt_list[i - 1] + suffix
            clip_seed = seed + i - 1 if vary_seed else seed
            matched = color_match if i > 1 and not reanchor else 0.0
            key_parts = [BACKEND, prompt, clip_seed, width, height, length, generation,
                         tensor_hash(first) if first is not None else None, tensor_hash(reference) if target else None]
            if voice_file:
                key_parts.append(["voice", os.path.basename(voice_file)])
            if matched:
                key_parts.append(["chroma", matched])
            key = hashlib.sha256(json.dumps(key_parts).encode()).hexdigest()
            video_path = os.path.join(cache_dir, f"{key}.mp4")
            last_path = os.path.join(cache_dir, f"{key}_last.png")
            cached = os.path.exists(video_path) and os.path.exists(last_path)
            if cached and not (redo_from and i >= redo_from):
                progress.skip_clip(i)
            else:
                progress.start_clip(i, clip_seed)
                # Written under temporary names and moved into place only once h3.c succeeded.
                partial_video = os.path.join(cache_dir, f"{key}.partial.mp4")
                partial_last = os.path.join(cache_dir, f"{key}_last.partial.png")

                def on_progress(phase, completed, total):
                    progress.update(phase, completed, total)
                    return comfy.model_management.processing_interrupted()

                try:
                    if matched:
                        # The previous clip's last frame drifts in color; pull its hue and saturation back toward the reference.
                        first_file = os.path.join(cache_dir, f"{key}_first.png")
                        save_png(match_chroma(first, reference, matched), first_file)
                    if worker is None:
                        progress.update("load model", 0, 1)
                        worker = get_worker(str(model_path(model_dir)))
                        progress.update("load model", 1, 1)
                    result = worker.generate({
                        "prompt": prompt, "width": width, "height": height, "frames": length, "seed": clip_seed,
                        "first_frame": None if voice_file else first_file, "last_frame": reference_file if target else None,
                        "ref_image": first_file if voice_file else None, "ref_audio": voice_file,
                        "output": partial_video, "last_frame_output": partial_last, "ssd_streaming": ssd_streaming, **generation,
                    }, on_progress)
                except BaseException as e:
                    progress.abort()
                    for path in (partial_video, partial_last):
                        with suppress(FileNotFoundError):
                            os.remove(path)
                    if isinstance(e, H3Cancelled):
                        comfy.model_management.throw_exception_if_processing_interrupted()
                    raise
                with open(os.path.join(cache_dir, f"{key}.json"), "w", encoding="utf-8") as f:
                    json.dump({"prompt": prompt, "seed": clip_seed, "frames": result["frames"], "seconds": result["seconds"],
                               "timings": result["timings"]}, f, indent=2, ensure_ascii=False)
                os.replace(partial_last, last_path)
                os.replace(partial_video, video_path)
                progress.end_clip()

            clip_video = InputImpl.VideoFromFile(video_path)
            if i > 1 and not reanchor and not voice_file:
                # Drop the first frame (and 1/24 s of audio): it duplicates the previous clip's last frame.
                clip_video = clip_video.as_trimmed(1 / FPS, 0, strict_duration=False)
            videos.append(clip_video)
            prev_last, prev_last_file = load_png(last_path), last_path
            if reference is None:
                # Text-to-video start: anchor the rest of the chain to the first clip's last frame.
                reference, reference_file = prev_last, prev_last_file

        progress.finish()
        return io.NodeOutput(InputImpl.VideoFromList(videos))
